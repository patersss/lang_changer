package org.chel.platform.windows;

/**
 * Шов вокруг API раскладок. Всё выражено в примитивах, чтобы логику выбора
 * цели и проверки результата можно было тестировать без нативных вызовов.
 */
public interface Win32Layout {

    /**
     * Окно, которому адресован ввод, и поток, которому принадлежит раскладка.
     * Раскладка в Windows привязана к потоку, а не к процессу.
     */
    record FocusTarget(int threadId, long window) {
    }

    /**
     * @return текущая цель ввода или null, если активного окна нет
     * (например, фокус на рабочем столе в момент перерисовки оболочки)
     */
    FocusTarget focus();

    /**
     * @return HKL раскладки указанного потока, 0 если поток недоступен
     */
    long currentLayout(int threadId);

    /**
     * Просит окно переключиться на следующую раскладку. Асинхронно:
     * возврат не означает, что раскладка уже сменилась.
     */
    void requestNextLayout(long window);
}
